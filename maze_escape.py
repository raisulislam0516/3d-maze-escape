def draw_minimap():
    n = MAZE_N
    box_left, box_bottom, box_size = 740, 540, 240

    glMatrixMode(GL_PROJECTION)
    glPushMatrix()
    glLoadIdentity()
    # Near Plane: -1.0, Far Plane: 1.0
    glOrtho(0, 1000, 0, 800, -1.0, 1.0)

    glMatrixMode(GL_MODELVIEW)
    glPushMatrix()
    glLoadIdentity()

    z = -0.999

    # 1. Minimap Base Box
    glColor3f(0.06, 0.06, 0.12)
    glBegin(GL_QUADS)
    glVertex3f(box_left, box_bottom, z)
    glVertex3f(box_left + box_size, box_bottom, z)
    glVertex3f(box_left + box_size, box_bottom + box_size, z)
    glVertex3f(box_left, box_bottom + box_size, z)
    glEnd()

    # Border Line
    glColor3f(0.0, 1.0, 0.4)
    glLineWidth(3.0)
    glBegin(GL_LINE_LOOP)
    glVertex3f(box_left, box_bottom, z)
    glVertex3f(box_left + box_size, box_bottom, z)
    glVertex3f(box_left + box_size, box_bottom + box_size, z)
    glVertex3f(box_left, box_bottom + box_size, z)
    glEnd()

    def to_map(wx, wy):
        mx = box_left + ((wx + CELL / 2.0) / (n * CELL)) * box_size
        my = box_bottom + ((wy + CELL / 2.0) / (n * CELL)) * box_size
        return mx, my

    # 2. Draw Maze Walls on Minimap
    glColor3f(0.2, 0.8, 0.3)
    glLineWidth(2.5)
    glBegin(GL_LINES)
    for (wx, wy, axis) in wall_list:
        if axis == 'X':
            x1, y1 = to_map(wx - CELL / 2.0, wy)
            x2, y2 = to_map(wx + CELL / 2.0, wy)
        else:
            x1, y1 = to_map(wx, wy - CELL / 2.0)
            x2, y2 = to_map(wx, wy + CELL / 2.0)
        glVertex3f(x1, y1, z)
        glVertex3f(x2, y2, z)
    glEnd()

    # 3. Draw Exit Door
    dx, dy = to_map(door_x, door_y)
    if door_open:
        glColor3f(0.0, 1.0, 0.0)
    else:
        glColor3f(1.0, 0.0, 0.0)
    glPointSize(10.0)
    glBegin(GL_POINTS)
    glVertex3f(dx, dy, z)
    glEnd()

    # 4. Draw Player Position & Direction
    px, py = to_map(player_x, player_y)

    # Player Dot
    glColor3f(1.0, 1.0, 1.0)
    glPointSize(8.0)
    glBegin(GL_POINTS)
    glVertex3f(px, py, z)
    glEnd()

    # Facing Line
    rad = math.radians(player_angle)
    dir_x = px + math.cos(rad) * 16
    dir_y = py + math.sin(rad) * 16
    glColor3f(1.0, 0.9, 0.0)
    glLineWidth(2.0)
    glBegin(GL_LINES)
    glVertex3f(px, py, z)
    glVertex3f(dir_x, dir_y, z)
    glEnd()

    glPopMatrix()
    glMatrixMode(GL_PROJECTION)
    glPopMatrix()
    glMatrixMode(GL_MODELVIEW)

def compass_hint():
    dx, dy = door_x - player_x, door_y - player_y
    dist = math.hypot(dx, dy)
    angle_to_door = math.degrees(math.atan2(dy, dx))
    rel = (angle_to_door - player_angle + 180) % 360 - 180
    if abs(rel) < 25: arrow = "AHEAD ^"
    elif abs(rel) > 155: arrow = "BEHIND v"
    elif rel > 0: arrow = "LEFT <"
    else: arrow = "RIGHT >"
    return "EXIT: {}  ({} units)".format(arrow, int(dist))

