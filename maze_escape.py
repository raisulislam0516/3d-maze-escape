def update_pickups():
    global gems_collected, score, combo_count, combo_timer, keys_collected
    if combo_timer > 0:
        combo_timer -= 1.0 / 60.0
        if combo_timer <= 0: combo_count = 0
    for g in gems:
        if not g['alive']: continue
        if circle_hit(player_x, player_y, g['x'], g['y'], 34):
            g['alive'] = False
            gems_collected += 1
            combo_count += 1
            combo_timer = COMBO_WINDOW
            score += 10 * min(combo_count, 5)

    for k in keys_list:
        if not k['alive']: continue
        if circle_hit(player_x, player_y, k['x'], k['y'], 34):
            k['alive'] = False
            keys_collected += 1
            score += 75

