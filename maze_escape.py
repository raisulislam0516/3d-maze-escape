def resolve_entity_collision(x, y, radius):
    for (minx, maxx, miny, maxy) in wall_boxes:
        cx = max(minx, min(x, maxx))
        cy = max(miny, min(y, maxy))
        dx, dy = x - cx, y - cy
        dist_sq = dx * dx + dy * dy
        if dist_sq < radius * radius:
            dist = math.sqrt(dist_sq) if dist_sq > 0.0001 else 0.0001
            push = radius - dist
            x += (dx / dist) * push
            y += (dy / dist) * push
    if door_box is not None and not door_open:
        minx, maxx, miny, maxy = door_box
        cx = max(minx, min(x, maxx))
        cy = max(miny, min(y, maxy))
        dx, dy = x - cx, y - cy
        dist_sq = dx * dx + dy * dy
        if dist_sq < radius * radius:
            dist = math.sqrt(dist_sq) if dist_sq > 0.0001 else 0.0001
            push = radius - dist
            x += (dx / dist) * push
            y += (dy / dist) * push
    return x, y

def resolve_collision(x, y):
    if god_mode:
        return x, y
    return resolve_entity_collision(x, y, PLAYER_R)
def has_line_of_sight(x1, y1, x2, y2, samples=6):
    for i in range(1, samples):
        t = i / float(samples)
        px = x1 + (x2 - x1) * t
        py = y1 + (y2 - y1) * t
        for (minx, maxx, miny, maxy) in wall_boxes:
            if minx <= px <= maxx and miny <= py <= maxy:
                return False
    return True
def circle_hit(px, py, hx, hy, r):
    dx, dy = px - hx, py - hy
    return (dx * dx + dy * dy) < r * r
def damage_player(amount):
    global player_health, hit_cooldown, game_state
    if god_mode or game_state != 'playing':
        return
    if hit_cooldown > 0:
        return
    player_health -= amount
