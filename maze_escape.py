def keyboardListener(key, x, y):
    global player_x, player_y, player_angle, camera_mode, god_mode, last_move_time
    if game_state == 'playing':
        if key == b'w':
            rad = math.radians(player_angle)
            nx = player_x + math.cos(rad) * PLAYER_SPEED
            ny = player_y + math.sin(rad) * PLAYER_SPEED
            player_x, player_y = resolve_collision(nx, ny)
            last_move_time = elapsed_time
        if key == b's':
            rad = math.radians(player_angle)
            nx = player_x - math.cos(rad) * PLAYER_SPEED
            ny = player_y - math.sin(rad) * PLAYER_SPEED
            player_x, player_y = resolve_collision(nx, ny)
            last_move_time = elapsed_time

        if key == b'a': player_angle = (player_angle + TURN_STEP) % 360
        if key == b'd': player_angle = (player_angle - TURN_STEP) % 360

    if key == b'c': god_mode = not god_mode
    if key == b'v': camera_mode = 'TOP' if camera_mode == 'FPV' else 'FPV'
    if key == b'r': init_game()
    glutPostRedisplay()

