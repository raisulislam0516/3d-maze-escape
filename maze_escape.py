def pick_unique(pool, count):
    pool = list(pool)
    random.shuffle(pool)
    return pool[:count]
def make_patrol_path(cx, cy, steps=4):
    path = [cell_center(cx, cy)]
    cur = (cx, cy)
    for _ in range(steps):
        d = open_dirs(cur[0], cur[1])
        if not d: break
        choice = random.choice(d)
        nx, ny = cur
        if choice == 'N': ny -= 1
        elif choice == 'S': ny += 1
        elif choice == 'E': nx += 1
        elif choice == 'W': nx -= 1
        if not (0 <= nx < MAZE_N and 0 <= ny < MAZE_N): break
        cur = (nx, ny)
        path.append(cell_center(nx, ny))
    return path
