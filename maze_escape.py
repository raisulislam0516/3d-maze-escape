def game_tick():
    global last_tick, elapsed_time, time_left, hit_cooldown, game_state, player_fire_cooldown

    now = time.time()
    dt = min(now - last_tick if last_tick else 0.0, 0.05)
    last_tick = now
    elapsed_time += dt

    if game_state != 'playing': return
    time_left -= dt
    if time_left <= 0:
        time_left = 0
        game_state = 'lost'
        return
    if hit_cooldown > 0: hit_cooldown -= dt
    if player_fire_cooldown > 0: player_fire_cooldown -= dt
    update_pickups()
    update_door()
    update_pendulums()
    update_lasers(dt)
    update_spikes(dt)
    update_soldiers(dt)
    update_bullets(dt)
    update_grenades(dt)
    update_explosions(dt)
    check_exit()

