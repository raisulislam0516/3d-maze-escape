def generate_maze(n):
    grid = {}
    for x in range(n):
        for y in range(n):
            grid[(x, y)] = {'N': True, 'S': True, 'E': True, 'W': True, 'visited': False}

    opp = {'N': 'S', 'S': 'N', 'E': 'W', 'W': 'E'}
    stack = [(0, 0)]
    grid[(0, 0)]['visited'] = True
    while stack:
        cx, cy = stack[-1]
        neighbours = []
        if cy > 0 and not grid[(cx, cy - 1)]['visited']:
            neighbours.append((cx, cy - 1, 'N'))
        if cy < n - 1 and not grid[(cx, cy + 1)]['visited']:
            neighbours.append((cx, cy + 1, 'S'))
        if cx > 0 and not grid[(cx - 1, cy)]['visited']:
            neighbours.append((cx - 1, cy, 'W'))
        if cx < n - 1 and not grid[(cx + 1, cy)]['visited']:
            neighbours.append((cx + 1, cy, 'E'))
        if not neighbours:
            stack.pop()
            continue
        nx, ny, d = random.choice(neighbours)
        grid[(cx, cy)][d] = False
        grid[(nx, ny)][opp[d]] = False
        grid[(nx, ny)]['visited'] = True
        stack.append((nx, ny))
    return grid
def cell_center(cx, cy):
    return cx * CELL, cy * CELL
def open_dirs(cx, cy):
    c = maze_grid[(cx, cy)]
    dirs = []
    if not c['N']: dirs.append('N')
    if not c['S']: dirs.append('S')
    if not c['E']: dirs.append('E')
    if not c['W']: dirs.append('W')
    return dirs
def cell_dist(a, b):
    return abs(a[0] - b[0]) + abs(a[1] - b[1])

def build_walls():
    global wall_list, wall_boxes
    wall_list = []
    wall_boxes = []
    n = MAZE_N
    for x in range(n):
        for y in range(n):
            c = maze_grid[(x, y)]
            if c['N']:
                wall_list.append((x * CELL, y * CELL - CELL / 2.0, 'X'))
            if c['W']:
                wall_list.append((x * CELL - CELL / 2.0, y * CELL, 'Y'))
            if y == n - 1 and c['S']:
                if x == n - 1:
                    continue
                wall_list.append((x * CELL, y * CELL + CELL / 2.0, 'X'))
            if x == n - 1 and c['E']:
                wall_list.append((x * CELL + CELL / 2.0, y * CELL, 'Y'))

    for (wx, wy, axis) in wall_list:
        if axis == 'X':
            wall_boxes.append((wx - (CELL + WALL_T) / 2.0, wx + (CELL + WALL_T) / 2.0,
                                wy - WALL_T / 2.0, wy + WALL_T / 2.0))
